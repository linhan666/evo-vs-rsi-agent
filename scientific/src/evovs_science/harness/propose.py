"""Let the agent propose a change to the harness itself.

This is the missing half of P4-04. Until now candidates could only be generated by
the operator with `evolution/propose.py`, so the "self-evolving" arm had no way to
act on what it learned during a run: R and M were behaviourally identical.

The tool writes a CandidateSpec that the existing shadow/gate pipeline can consume
unchanged. It does not promote anything — promotion stays with the gate and the
operator — so the safety property "a candidate never edits src/lib directly" holds.

Spec shape mirrors `evolution/candidates/*.json`; `evolution/spec.py` validates on
the way in, so a malformed proposal fails here rather than at promotion time.
"""
from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

SPEC_VERSION = "0.1.0-agent"


def _slug(value: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", value.lower()).strip("-")


def main(argv: list[str] | None = None) -> int:
    import argparse
    parser = argparse.ArgumentParser(prog="evovs_science.harness.propose")
    parser.add_argument("--candidate-id", required=True)
    parser.add_argument("--hypothesis", required=True)
    parser.add_argument("--risk", required=True)
    parser.add_argument("--change-key", required=True, help="e.g. preflight:ml.train")
    parser.add_argument("--change-value", required=True)
    parser.add_argument("--acceptance-json", required=True,
                        help='JSON object, e.g. {"equivalence":1.0,"early_rejection":true}')
    parser.add_argument("--output-dir", default="harness_candidates")
    parser.add_argument("--change-type", default="experiment",
                        choices=["env", "experiment"], help="`env` is replayable by shadow")
    args = parser.parse_args(argv)

    try:
        acceptance = json.loads(args.acceptance_json)
    except ValueError as error:
        print(f"INVALID_SPEC: acceptance-json is not JSON ({error})", file=sys.stderr)
        return 2
    if not isinstance(acceptance, dict) or not acceptance:
        print("INVALID_SPEC: acceptance must be a non-empty object", file=sys.stderr)
        return 2

    candidate_id = _slug(args.candidate_id)
    if len(candidate_id) < 3:
        print("INVALID_SPEC: candidate-id collapses to fewer than 3 characters", file=sys.stderr)
        return 2

    spec = {
        "candidate_id": candidate_id,
        "version": SPEC_VERSION,
        "status": "proposal",
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "hypothesis": args.hypothesis,
        "risk": args.risk,
        "changes": [{"type": args.change_type, "key": args.change_key, "value": args.change_value}],
        "acceptance": acceptance,
        "basis": {
            "generated_by": "evovs_science.harness.propose (agent)",
            "kind": "agent-proposal",
            "note": "proposed from the traces of this run; shadow replay and the gate decide",
        },
    }

    target = Path(args.output_dir)
    target.mkdir(parents=True, exist_ok=True)
    path = target / f"{candidate_id}.json"
    path.write_text(json.dumps(spec, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(str(path))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
